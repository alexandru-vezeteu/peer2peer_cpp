// ─────────────────────────────────────────────────────────────────────────────

static void run_tests()
{
    // ── Poly1305 key derivation (chacha_20::subkey) ──────────────────────────
    {
        auto got = chacha_20::subkey(a4tv1_key, a4tv1_nonce);
        TEST("RFC8439 §A.4 TV#1: Poly1305 key derivation (zero key)", got == a4tv1_otk);
    }
    {
        auto got = chacha_20::subkey(a4tv2_key, a4tv2_nonce);
        TEST("RFC8439 §A.4 TV#2: Poly1305 key derivation", got == a4tv2_otk);
    }
    {
        auto got = chacha_20::subkey(a4tv3_key, a4tv3_nonce);
        TEST("RFC8439 §A.4 TV#3: Poly1305 key derivation", got == a4tv3_otk);
    }

    // ── AEAD open (§A.5 vector — decryption path) ────────────────────────────
    {
        // Pack ciphertext || tag as the blob that open() expects
        std::vector<uint8_t> blob(a5_ciphertext.begin(), a5_ciphertext.end());
        blob.insert(blob.end(), a5_tag.begin(), a5_tag.end());

        auto plaintext = chacha20_poly1305::open(
            a5_key,
            a5_nonce,
            blob,
            a5_aad);

        TEST("RFC8439 §A.5: AEAD open succeeds (non-empty plaintext)", !plaintext.empty());
        // The decrypted plaintext should re-encrypt to the known ciphertext
        if (!plaintext.empty())
        {
            auto resealed = chacha20_poly1305::seal(
                a5_key, a5_nonce,
                std::span<uint8_t>{plaintext},
                a5_aad);
            std::vector<uint8_t> expected(a5_ciphertext.begin(), a5_ciphertext.end());
            expected.insert(expected.end(), a5_tag.begin(), a5_tag.end());
            TEST("RFC8439 §A.5: re-seal round-trip matches original blob", resealed == expected);
        }
    }

    // ── AEAD open with corrupted tag must fail ────────────────────────────────
    {
        std::vector<uint8_t> blob(a5_ciphertext.begin(), a5_ciphertext.end());
        auto bad_tag = a5_tag;
        bad_tag[0] ^= 0xff; // flip one bit
        blob.insert(blob.end(), bad_tag.begin(), bad_tag.end());

        auto result = chacha20_poly1305::open(a5_key, a5_nonce, blob, a5_aad);
        TEST("RFC8439 §A.5: AEAD open rejects corrupted tag", result.empty());
    }

    // ── AEAD open with corrupted AAD must fail ───────────────────────────────
    {
        std::vector<uint8_t> blob(a5_ciphertext.begin(), a5_ciphertext.end());
        blob.insert(blob.end(), a5_tag.begin(), a5_tag.end());

        std::array<uint8_t, 12> bad_aad = a5_aad;
        bad_aad[0] ^= 0x01;

        auto result = chacha20_poly1305::open(a5_key, a5_nonce, blob, bad_aad);
        TEST("RFC8439 §A.5: AEAD open rejects corrupted AAD", result.empty());
    }

    // ── AEAD open with truncated blob must fail ───────────────────────────────
    {
        // blob shorter than tag_size
        std::vector<uint8_t> blob(a5_tag.begin(), a5_tag.begin() + 8); // only 8 bytes
        auto result = chacha20_poly1305::open(a5_key, a5_nonce, blob, a5_aad);
        TEST("AEAD open rejects truncated blob (< tag_size)", result.empty());
    }
}

int main()
{
    run_tests();
    std::println("\n{} passed, {} failed", passed, failed);
    return failed ? 1 : 0;
}
